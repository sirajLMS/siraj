import { Stack } from "@mui/material";
import type { ReactNode } from "react";
import { AutoGeneratedBadge } from "@/frontend/common/components/ui/display/meetingConfig/AutoGeneratedBadge";
import {
  MeetingConfigList,
  type MeetingConfigListItem,
} from "@/frontend/common/components/ui/display/meetingConfig/MeetingConfigList";
import { AutoGenerationSupportCallout } from "@/frontend/common/views/dashboard/profile/shared/meeting-configs/AutoGenerationSupportCallout";
import {
  type LinkedClassInstance,
  LinkedClassInstancesList,
} from "@/frontend/common/views/dashboard/profile/shared/meeting-configs/LinkedClassInstancesList";
import { noop } from "@/frontend/common/views/dashboard/profile/shared/meeting-configs/MeetingConfigsManager.stories.fixtures";
import {
  autoGenLabels,
  linkedLabels,
  reauthLabels,
} from "@/frontend/common/views/dashboard/profile/shared/meeting-configs/MeetingConfigsManager.stories.labels";
import { ReauthNeededBanner } from "@/frontend/common/views/dashboard/profile/shared/meeting-configs/reauth-needed-banner";
import type { ReauthProvider } from "@/frontend/common/views/dashboard/profile/shared/meeting-configs/reauth-needed-banner.types";
import { ViewBookingsLink } from "@/frontend/common/views/dashboard/profile/shared/meeting-configs/ViewBookingsLink";

interface RowExtraProps {
  configId: string;
  meetingId: string | null;
  meetingUrl: string | null;
  providerName: string;
  providerKind: string;
  instances: readonly LinkedClassInstance[];
  showInstances: boolean;
}

function RowExtra({
  configId,
  meetingId,
  meetingUrl,
  providerName,
  providerKind,
  instances: rowInstances,
  showInstances,
}: Readonly<RowExtraProps>) {
  return (
    <Stack spacing={1} sx={{ mt: 1 }}>
      <Stack sx={{ flexDirection: "row", alignItems: "center", gap: 1, flexWrap: "wrap" }}>
        <AutoGeneratedBadge
          meetingId={meetingId}
          meetingUrl={meetingUrl}
          providerName={providerName}
          providerKind={providerKind}
          onRegenerate={noop}
        />
        <ViewBookingsLink meetingConfigId={configId} labels={linkedLabels} onViewBookings={noop} />
      </Stack>
      {showInstances ? (
        <LinkedClassInstancesList meetingConfigId={configId} instances={rowInstances} labels={linkedLabels} />
      ) : null}
    </Stack>
  );
}

type RenderRowExtraFn = (c: { id?: string | null }) => ReactNode;

function makeRowExtraRenderer(props: Omit<RowExtraProps, "configId">): RenderRowExtraFn {
  const renderer = (c: { id?: string | null }) => <RowExtra configId={c.id ?? ""} {...props} />;
  renderer.displayName = "RowExtraRenderer";
  return renderer;
}

interface ConfigStoryConfig {
  config: MeetingConfigListItem;
  width: number;
  showAutoGenCallout?: boolean;
  rowExtra: Omit<RowExtraProps, "configId">;
}

interface ConfigStoryResult {
  readonly render: () => React.JSX.Element;
  readonly args: { readonly configs: readonly MeetingConfigListItem[] };
}

export function createConfigStory(config: ConfigStoryConfig): ConfigStoryResult {
  return {
    render: () => (
      <Stack spacing={2} sx={{ width: config.width }}>
        {config.showAutoGenCallout ? <AutoGenerationSupportCallout labels={autoGenLabels} /> : null}
        <MeetingConfigList
          configs={[config.config]}
          title="Meeting Configurations"
          renderRowExtra={makeRowExtraRenderer(config.rowExtra)}
        />
      </Stack>
    ),
    args: { configs: [] },
  };
}

interface BannerStoryResult {
  readonly render: () => React.JSX.Element;
  readonly args: { readonly configs: readonly MeetingConfigListItem[] };
}

export function createBannerStory({
  reauthProviders,
}: {
  reauthProviders: readonly ReauthProvider[];
}): BannerStoryResult {
  return {
    render: () => (
      <Stack spacing={2} sx={{ width: 500 }}>
        <AutoGenerationSupportCallout labels={autoGenLabels} />
        <ReauthNeededBanner reauthProviders={reauthProviders} labels={reauthLabels} onReconnect={noop} />
      </Stack>
    ),
    args: { configs: [] },
  };
}
