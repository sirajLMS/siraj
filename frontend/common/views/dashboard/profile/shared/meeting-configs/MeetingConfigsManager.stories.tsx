interface RowExtraProps {
  configId: string;
  meetingId: string | null;
  meetingUrl: string | null;
  providerName: string;
  providerKind: string;
  instances: readonly LinkedClassInstance[];
  showInstances: boolean;
}

function RowExtra({
  configId,
  meetingId,
  meetingUrl,
  providerName,
  providerKind,
  instances: rowInstances,
  showInstances,
}: RowExtraProps) {
  return (
    <Stack spacing={1} sx={{ mt: 1 }}>
      <Stack sx={{ flexDirection: "row", alignItems: "center", gap: 1, flexWrap: "wrap" }}>
        <AutoGeneratedBadge
          meetingId={meetingId}
          meetingUrl={meetingUrl}
          providerName={providerName}
          providerKind={providerKind}
          onRegenerate={noop}
        />
        <ViewBookingsLink meetingConfigId={configId} labels={linkedLabels} onViewBookings={noop} />
      </Stack>
      {showInstances ? (
        <LinkedClassInstancesList meetingConfigId={configId} instances={rowInstances} labels={linkedLabels} />
      ) : null}
    </Stack>
  );
}

type RenderRowExtraFn = (c: { id?: string | null }) => React.ReactNode;

function makeRowExtraRenderer(props: Omit<RowExtraProps, "configId">): RenderRowExtraFn {
  const renderer = (c: { id?: string | null }) => <RowExtra configId={c.id ?? ""} {...props} />;
  renderer.displayName = "RowExtraRenderer";
  return renderer;
}

interface ConfigStoryConfig {
  config: MeetingConfigListItem;
  width: number;
  showAutoGenCallout?: boolean;
  rowExtra: Omit<RowExtraProps, "configId">;
}

function renderConfigStory({
  config,
  width,
  showAutoGenCallout = false,
  rowExtra,
}: ConfigStoryConfig): React.JSX.Element {
  return (
    <Stack spacing={2} sx={{ width }}>
      {showAutoGenCallout ? <AutoGenerationSupportCallout labels={autoGenLabels} /> : null}
      <MeetingConfigList
        configs={[config]}
        title="Meeting Configurations"
        renderRowExtra={makeRowExtraRenderer(rowExtra)}
      />
    </Stack>
  );
}

interface BannerStoryConfig {
  reauthProviders: readonly ReauthProvider[];
}

function renderBannerStory({ reauthProviders }: BannerStoryConfig): React.JSX.Element {
  return (
    <Stack spacing={2} sx={{ width: 500 }}>
      <AutoGenerationSupportCallout labels={autoGenLabels} />
      <ReauthNeededBanner reauthProviders={reauthProviders} labels={reauthLabels} onReconnect={noop} />
    </Stack>
  );
}

function createConfigStory(config: ConfigStoryConfig): Pick<Story, "render" | "args"> {
  return {
    render: () => renderConfigStory(config),
    args: { configs: [] },
  };
}

function createBannerStory(config: BannerStoryConfig): Pick<Story, "render" | "args"> {
  return {
    render: () => renderBannerStory(config),
    args: { configs: [] },
  };
}

