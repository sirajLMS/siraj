function makeConfig(overrides: {
  id: string;
  providerName: string;
  providerSlug: string;
  providerKind: string;
  providerId: string;
  meetingUrl?: string | null;
  label?: string | null;
  isDefault?: boolean;
  hasSecret?: boolean;
}): MeetingConfigListItem {
  return {
    id: overrides.id,
    userId: "user-1",
    providerId: overrides.providerId,
    label: overrides.label ?? null,
    isDefault: overrides.isDefault ?? false,
    hasSecret: overrides.hasSecret ?? false,
    providerMetadata: null,
    createdAt: "2026-01-15T10:00:00Z",
    updatedAt: "2026-01-20T12:00:00Z",
    details: {
      meetingUrl: overrides.meetingUrl ?? null,
      username: null,
      tenantId: null,
    },
    provider: {
      id: overrides.providerId,
      slug: overrides.providerSlug,
      name: { en: overrides.providerName, ar: overrides.providerName },
      description: null,
      instructions: null,
      urlAllowlist: [],
      urlExample: "https://example.com",
      logoUrl: null,
      providerKind: overrides.providerKind,
      isActive: true,
      createdAt: "2026-01-01T00:00:00Z",
      updatedAt: "2026-01-01T00:00:00Z",
      fieldSchema: null,
    },
  } as unknown as MeetingConfigListItem;
}

