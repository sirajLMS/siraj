type ProviderMeta = { meetingId?: string; spaceName?: string };

function isProviderMeta(value: unknown): value is ProviderMeta {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return false;
  }
  const meetingId = "meetingId" in value ? value.meetingId : undefined;
  const spaceName = "spaceName" in value ? value.spaceName : undefined;
  const meetingIdValid = meetingId === undefined || typeof meetingId === "string";
  const spaceNameValid = spaceName === undefined || typeof spaceName === "string";
  return meetingIdValid && spaceNameValid;
}

type RenderRowExtraArgs = {
  readonly state: ReturnType<typeof useMeetingConfigsManagerViewModel>;
  readonly locale: string;
};

function renderRowExtraRow(config: MeetingConfigListItem, state: RenderRowExtraArgs["state"], locale: string) {
  const configId = config.id ?? "";
  const providerKind = config.provider?.providerKind ?? "manual";
  const providerName = config.provider?.name
    ? resolveLocalizedString(config.provider.name, locale)
    : (config.provider?.slug ?? "");
  const providerMeta =
    config.providerMetadata != null && isProviderMeta(config.providerMetadata) ? config.providerMetadata : null;
  const meetingId = providerMeta?.meetingId ?? providerMeta?.spaceName ?? null;
  const meetingUrl = config.details?.meetingUrl ?? null;
  const isExpanded = state.expandedBookingsId === configId;
  const instances = state.bookingsInstances.get(configId) ?? [];
  const showInstances = isExpanded && (state.bookingsLoading || instances.length > 0);

  return (
    <Stack spacing={1} sx={{ mt: 1 }}>
      <Stack sx={{ flexDirection: "row", alignItems: "center", gap: 1, flexWrap: "wrap" }}>
        <AutoGeneratedBadge
          meetingId={meetingId}
          meetingUrl={meetingUrl}
          providerName={providerName}
          providerKind={providerKind}
          onRegenerate={() => state.regenerateConfig(configId)}
          regenerating={state.generating}
        />
        <ViewBookingsLink
          meetingConfigId={configId}
          labels={state.labels.linkedClassInstances}
          onViewBookings={state.handleViewBookings}
        />
      </Stack>
      {showInstances ? (
        <LinkedClassInstancesList
          meetingConfigId={configId}
          instances={instances}
          loading={state.bookingsLoading}
          emptyMessage={state.labels.linkedClassInstances.linkedClassInstancesEmpty}
          labels={state.labels.linkedClassInstances}
        />
      ) : null}
    </Stack>
  );
}

function renderRowExtraFactory({ state, locale }: RenderRowExtraArgs) {
  return function renderRowExtra(config: MeetingConfigListItem) {
    return renderRowExtraRow(config, state, locale);
  };
}

function buildProviderNameMap(
  connectProviderAccountItems: ReturnType<typeof useMeetingConfigsManagerViewModel>["connectProviderAccountItems"],
  configs: readonly UserMeetingConfigFieldsFragment[],
  locale: string
): Map<string, string> {
  const map = new Map<string, string>();
  for (const item of connectProviderAccountItems) {
    map.set(item.providerSlug, item.providerName);
  }
  for (const c of configs) {
    const slug = c.provider?.slug;
    if (slug && !map.has(slug)) {
      map.set(slug, c.provider?.name ? resolveLocalizedString(c.provider.name, locale) : slug);
    }
  }
  return map;
}

