export type MeetingConfigsManagerProps = {
  readonly targetUserId: string;
  readonly canManage: boolean;
};

type ProviderMeta = { meetingId?: string; spaceName?: string };

function isProviderMeta(value: unknown): value is ProviderMeta {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return false;
  }
  const meetingId = "meetingId" in value ? value.meetingId : undefined;
  const spaceName = "spaceName" in value ? value.spaceName : undefined;
  const meetingIdValid = meetingId === undefined || typeof meetingId === "string";
  const spaceNameValid = spaceName === undefined || typeof spaceName === "string";
  return meetingIdValid && spaceNameValid;
}

function AddConfigButton({ onClick, label }: { readonly onClick: () => void; readonly label: string }) {
  return (
    <Stack sx={{ flexDirection: "row", justifyContent: "flex-end" }}>
      <Button variant="contained" startIcon={<AddOutlinedIcon />} onClick={onClick}>
        {label}
      </Button>
    </Stack>
  );
}

type MeetingConfigDialogsProps = {
  readonly targetUserId: string;
  readonly editConfig: UserMeetingConfigFieldsFragment | null;
  readonly formOpen: boolean;
  readonly deleteId: string | null;
  readonly deleteLabel: string;
  readonly deleting: boolean;
  readonly showSuccess: boolean;
  readonly errorMessage: string | null;
  readonly existingCount: number;
  readonly onCloseForm: () => void;
  readonly onSaved: () => void;
  readonly onCloseDelete: () => void;
  readonly onConfirmDelete: () => void;
  readonly onCloseSuccess: () => void;
  readonly onCloseError: () => void;
  readonly successMessage: string;
  readonly managerLabels: ReturnType<typeof useMeetingConfigsManagerViewModel>["labels"]["manager"];
};

function MeetingConfigDialogs({
  targetUserId,
  editConfig,
  formOpen,
  deleteId,
  deleteLabel,
  deleting,
  showSuccess,
  errorMessage,
  existingCount,
  onCloseForm,
  onSaved,
  onCloseDelete,
  onConfirmDelete,
  onCloseSuccess,
  onCloseError,
  successMessage,
  managerLabels,
}: MeetingConfigDialogsProps) {
  return (
    <>
      <MeetingConfigFormDialog
        open={formOpen}
        userId={targetUserId}
        editConfig={editConfig}
        existingCount={existingCount}
        labels={managerLabels}
        onClose={onCloseForm}
        onSaved={onSaved}
      />

      <MeetingConfigDeleteDialog
        open={deleteId != null}
        configLabel={deleteLabel}
        isLoading={deleting}
        labels={managerLabels}
        onClose={onCloseDelete}
        onConfirm={onConfirmDelete}
      />

      <FormSuccessSnackbar open={showSuccess} message={successMessage} onClose={onCloseSuccess} />
      <FormErrorSnackbar open={errorMessage != null} message={errorMessage ?? ""} onClose={onCloseError} />
    </>
  );
}

export function MeetingConfigsManager({ targetUserId, canManage }: MeetingConfigsManagerProps) {
  const state = useMeetingConfigsManagerViewModel({ targetUserId });
  const locale = useAppLocale();
  const { t, configs, loading, error, refetch } = state;
  const [disconnectTarget, setDisconnectTarget] = useState<string | null>(null);

  const handleDisconnectRequest = (providerSlug: string) => {
    setDisconnectTarget(providerSlug);
  };

  const handleDisconnectConfirm = () => {
    if (disconnectTarget) {
      void state.disconnectProvider(disconnectTarget);
    }
    setDisconnectTarget(null);
  };

  const handleDisconnectCancel = () => {
    setDisconnectTarget(null);
  };

  if (error && configs.length === 0) {
    return (
      <ErrorState
        embedded
        message={t.loadError}
        retryLabel={t.retry}
        onRetry={() => {
          void refetch();
        }}
      />
    );
  }

  const busy = loading || state.deleting || state.settingDefault;
  const reconnectSlugs = state.requiresReconnect.map(r => r.providerSlug);

  const renderRowExtra = (config: MeetingConfigListItem) => {
    const configId = config.id ?? "";
    const providerKind = config.provider?.providerKind ?? "manual";
    const providerName = config.provider?.name
      ? resolveLocalizedString(config.provider.name, locale)
      : (config.provider?.slug ?? "");
    const providerMeta =
      config.providerMetadata != null && isProviderMeta(config.providerMetadata) ? config.providerMetadata : null;
    const meetingId = providerMeta?.meetingId ?? providerMeta?.spaceName ?? null;
    const meetingUrl = config.details?.meetingUrl ?? null;
    const isExpanded = state.expandedBookingsId === configId;
    const instances = state.bookingsInstances.get(configId) ?? [];
    const showInstances = isExpanded && (state.bookingsLoading || instances.length > 0);

    return (
      <Stack spacing={1} sx={{ mt: 1 }}>
        <Stack sx={{ flexDirection: "row", alignItems: "center", gap: 1, flexWrap: "wrap" }}>
          <AutoGeneratedBadge
            meetingId={meetingId}
            meetingUrl={meetingUrl}
            providerName={providerName}
            providerKind={providerKind}
            onRegenerate={() => state.regenerateConfig(configId)}
            regenerating={state.generating}
          />
          <ViewBookingsLink
            meetingConfigId={configId}
            labels={state.labels.linkedClassInstances}
            onViewBookings={state.handleViewBookings}
          />
        </Stack>
        {showInstances ? (
          <LinkedClassInstancesList
            meetingConfigId={configId}
            instances={instances}
            loading={state.bookingsLoading}
            emptyMessage={state.labels.linkedClassInstances.linkedClassInstancesEmpty}
            labels={state.labels.linkedClassInstances}
          />
        ) : null}
      </Stack>
    );
  };

  return (
    <Stack spacing={2}>
      <AutoGenerationSupportCallout labels={state.labels.autoGeneration} />

      {state.reauthProviders.length > 0 ? (
        <ReauthNeededBanner
          reauthProviders={state.reauthProviders}
          labels={state.labels.reauthNeeded}
          onReconnect={state.onReconnect}
        />
      ) : null}

      {canManage ? <AddConfigButton onClick={state.openCreateForm} label={t.add} /> : null}

      {canManage && state.connectProviderAccountItems.length > 0 ? (
        <Stack spacing={1.5}>
          {state.connectProviderAccountItems.map(item => (
            <ConnectProviderAccount
              key={item.providerSlug}
              providerSlug={item.providerSlug}
              providerName={item.providerName}
              connectionState={item.connectionState}
              connectedEmail={item.connectedEmail}
              onConnect={state.connectProvider}
              onDisconnect={handleDisconnectRequest}
              loading={state.disconnecting}
            />
          ))}
        </Stack>
      ) : null}

      <MeetingConfigList
        configs={configs}
        loading={busy}
        title={t.listTitle}
        emptyMessage={loading ? undefined : t.empty}
        onEditAction={canManage ? state.openEditForm : undefined}
        onDeleteAction={canManage ? state.setDeleteId : undefined}
        onSetDefaultAction={canManage ? state.handleSetDefault : undefined}
        requiresReconnect={reconnectSlugs}
        renderRowExtra={renderRowExtra}
      />

      <MeetingConfigDialogs
        targetUserId={targetUserId}
        editConfig={state.editConfig}
        formOpen={state.formOpen}
        deleteId={state.deleteId}
        deleteLabel={state.deleteLabel}
        deleting={state.deleting}
        showSuccess={state.showSuccess}
        errorMessage={state.errorMessage}
        existingCount={configs.length}
        onCloseForm={state.closeForm}
        onSaved={state.handleSaved}
        onCloseDelete={() => state.setDeleteId(null)}
        onConfirmDelete={state.handleConfirmDelete}
        onCloseSuccess={() => state.setShowSuccess(false)}
        onCloseError={() => state.setErrorMessage(null)}
        successMessage={t.saved}
        managerLabels={state.labels.manager}
      />

      <DisconnectConfirmDialog
        labels={state.labels.connectAccount}
        open={disconnectTarget !== null}
        disconnecting={state.disconnecting}
        onConfirm={handleDisconnectConfirm}
        onCancel={handleDisconnectCancel}
      />
    </Stack>
  );
}
