"use client";

import AutoModeOutlinedIcon from "@mui/icons-material/AutoModeOutlined";
import RefreshOutlinedIcon from "@mui/icons-material/RefreshOutlined";
import { Chip, CircularProgress, ListItemIcon, ListItemText, Menu, MenuItem, Tooltip } from "@mui/material";
import { useCallback, useState } from "react";
import { type MeetingConfigDisplayLabels, Translation, useAppTranslation } from "@/shared/locale";

export interface AutoGeneratedBadgeProps {
  readonly meetingId: string | null;
  readonly meetingUrl: string | null;
  readonly providerName: string;
  readonly providerKind: string;
  readonly onRegenerate?: () => void;
  readonly regenerating?: boolean;
}

export function AutoGeneratedBadge({
  meetingId,
  meetingUrl,
  providerName,
  providerKind,
  onRegenerate,
  regenerating = false,
}: Readonly<AutoGeneratedBadgeProps>): React.ReactNode {
  const t = useAppTranslation(Translation.Ui.MeetingConfig);
  const tDisplay: MeetingConfigDisplayLabels = t.display;
  const [anchorEl, setAnchorEl] = useState<HTMLElement | null>(null);
  const open = Boolean(anchorEl);

  const handleClick = useCallback((event: React.MouseEvent<HTMLElement>) => {
    event.stopPropagation();
    setAnchorEl(event.currentTarget);
  }, []);

  const handleClose = useCallback(() => {
    setAnchorEl(null);
  }, []);

  const handleRegenerate = useCallback(() => {
    setAnchorEl(null);
    onRegenerate?.();
  }, [onRegenerate]);

  if (providerKind === "manual") {
    return null;
  }

  let tooltipText: string;
  if (meetingUrl) {
    tooltipText = `${tDisplay.autoGeneratedTooltip} — ${meetingUrl}`;
  } else if (meetingId) {
    tooltipText = `${tDisplay.autoGeneratedTooltip} — ${providerName} #${meetingId}`;
  } else {
    tooltipText = `${tDisplay.autoGeneratedTooltip} — ${providerName}`;
  }

  return (
    <>
      <Tooltip title={tooltipText}>
        <Chip
          size="small"
          color="primary"
          variant="outlined"
          label={tDisplay.autoGeneratedLabel}
          icon={<AutoModeOutlinedIcon sx={{ fontSize: 16 }} />}
          onClick={handleClick}
          sx={theme => ({
            cursor: "pointer",
            color: theme.palette.primary.main,
          })}
        />
      </Tooltip>

      <Menu
        anchorEl={anchorEl}
        open={open}
        onClose={handleClose}
        anchorOrigin={{ vertical: "bottom", horizontal: "left" }}
        transformOrigin={{ vertical: "top", horizontal: "left" }}
        slotProps={{
          paper: {
            sx: theme => ({
              minWidth: 180,
              boxShadow: theme.palette.shadow.card,
              border: `1px solid ${theme.palette.outlineVariant}`,
              borderRadius: 2,
            }),
          },
        }}
      >
        <MenuItem onClick={handleRegenerate} disabled={regenerating}>
          <ListItemIcon sx={{ minWidth: 32 }}>
            {regenerating ? <CircularProgress size={18} /> : <RefreshOutlinedIcon fontSize="small" />}
          </ListItemIcon>
          <ListItemText
            primary={regenerating ? tDisplay.regenerating : tDisplay.regenerateAction}
            slotProps={{
              primary: {
                sx: { typography: "bodyMd" },
              },
            }}
          />
        </MenuItem>
      </Menu>
    </>
  );
}
