function renderDialog(props: Partial<React.ComponentProps<typeof MeetingConfigFormDialog>> = {}) {
  return renderWithWrapper(
    <MeetingConfigFormDialog
      open
      userId="user-1"
      editConfig={null}
      existingCount={0}
      labels={managerLabels}
      onClose={mock(() => {})}
      onSaved={mock(() => {})}
      {...props}
    />
  );
}

describe("MeetingConfigFormDialog", () => {
  test("renders dialog content when open", () => {
    renderDialog();
    expect(screen.getByText("الاسم")).toBeInTheDocument();
    expect(screen.getByText("المزود")).toBeInTheDocument();
  });

  test("does not render dialog content when closed", () => {
    renderDialog({ open: false });
    expect(screen.queryByText("الاسم")).not.toBeInTheDocument();
  });

  test("calls onClose when cancel button clicked", () => {
    const onClose = mock(() => {});
    renderDialog({ onClose });
    fireEvent.click(screen.getByText("إلغاء"));
    expect(onClose).toHaveBeenCalledTimes(1);
  });

  test("shows save button", () => {
    renderDialog();
    expect(screen.getByText("حفظ")).toBeInTheDocument();
  });

  test("renders test config button when enhancementLabels provided", () => {
    renderDialog({
      enhancementLabels: {
        testConfig: "اختبار",
        previewUrlGenerated: "تم توليد الرابط",
        copyMeetingUrl: "نسخ الرابط",
      },
    });
    expect(screen.getByText("اختبار")).toBeInTheDocument();
  });

  test("does not render test config when enhancementLabels not provided", () => {
    renderDialog();
    expect(screen.queryByText("اختبار")).not.toBeInTheDocument();
  });
});
