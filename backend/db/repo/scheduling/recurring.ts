/**
 * Resolve the rate snapshot (amount + currency + source) for the class
 * instances generated by a new recurring schedule. Captured at booking time
 * so future rate changes don't affect already-scheduled classes.
 *
 * Precedence: recurring schedule rate > subject rate > teacher rate.
 * (Instance override is not applicable at booking time — it's set later by
 * an admin via `overrideClassInstanceRate`.)
 */
/**
 * Fetches raw rate data from the DB (subject + teacher rates) so the service
 * layer can call `resolveClassRate` with this data to compute the final snapshot.
 */
export async function fetchRawRateData(
  t: DBTransaction,
  recurringSchedule: {
    hourlyRate: string | null;
    rateCurrency: CurrencyCode | null;
    subjectId: string;
    teacherId: string;
  }
): Promise<{
  recurringSchedule: { hourlyRate: string | null; rateCurrency: CurrencyCode | null };
  subject: { hourlyRate: string | null; rateCurrency: CurrencyCode | null } | null;
  teacher: { hourlyRate: string | null; rateCurrency: CurrencyCode | null };
}> {
  const [subjectRow] = await t
    .select({ hourlyRate: classSubjects.hourlyRate, rateCurrency: classSubjects.rateCurrency })
    .from(classSubjects)
    .where(eq(classSubjects.id, recurringSchedule.subjectId))
    .limit(1);
  const [teacherRow] = await t
    .select({ hourlyRate: teachers.hourlyRate, rateCurrency: teachers.rateCurrency })
    .from(teachers)
    .where(eq(teachers.id, recurringSchedule.teacherId))
    .limit(1);

  return {
    recurringSchedule: { hourlyRate: recurringSchedule.hourlyRate, rateCurrency: recurringSchedule.rateCurrency },
    subject: subjectRow ?? null,
    teacher: teacherRow ?? { hourlyRate: null, rateCurrency: null },
  };
}

function computeScheduledStartForDay(
  dayOfWeek: string,
  startTime: string,
  effectiveStartDate: Date,
  weekOffset: number,
  timezone: string
): Date {
  const dayMap: Record<string, number> = {
    SUNDAY: 0,
    MONDAY: 1,
    TUESDAY: 2,
    WEDNESDAY: 3,
    THURSDAY: 4,
    FRIDAY: 5,
    SATURDAY: 6,
  };

  const targetDay = dayMap[dayOfWeek];
  const startDay = effectiveStartDate.getUTCDay();
  let daysUntilTarget = targetDay - startDay;
  if (daysUntilTarget < 0) daysUntilTarget += 7;
  daysUntilTarget += weekOffset * 7;

  const [hours, minutes] = startTime.split(":").map(Number);

  const result = new Date(effectiveStartDate);
  result.setUTCDate(result.getUTCDate() + daysUntilTarget);

  const year = result.getUTCFullYear();
  const month = result.getUTCMonth();
  const date = result.getUTCDate();

  const guess = new Date(Date.UTC(year, month, date, hours, minutes, 0, 0));

  const getOffsetMs = (d: Date) => {
    try {
      return getTimezoneOffsetMs(timezone, d);
    } catch {
      return 0;
    }
  };

  const offsetMs = getOffsetMs(guess);

  return new Date(guess.getTime() - offsetMs);
}

export async function deleteRecurringClass(
  classInstanceId: string,
  tx?: DBTransaction
): Promise<{ id: string; studentId: string; quotaDeducted: boolean; quotaId: string | null; deleted: boolean } | null> {
  const runner = async (t: DBTransaction) => {
    const now = new Date();

    const [existing] = await t
      .select({
        id: classInstances.id,
        quotaDeducted: classInstances.quotaDeducted,
        deletedAt: classInstances.deletedAt,
        studentId: classInstances.studentId,
        recurringScheduleId: classInstances.recurringScheduleId,
      })
      .from(classInstances)
      .where(eq(classInstances.id, classInstanceId))
      .limit(1);

    if (!existing) return null;

    // Resolve the quotaId from the parent recurring schedule
    let quotaId: string | null = null;
    if (existing.quotaDeducted && existing.recurringScheduleId) {
      const [schedule] = await t
        .select({ quotaId: recurringSchedules.quotaId })
        .from(recurringSchedules)
        .where(eq(recurringSchedules.id, existing.recurringScheduleId))
        .limit(1);
      quotaId = schedule?.quotaId ?? null;
    }

    const [deleted] = await t
      .update(classInstances)
      .set({
        deletedAt: now,
        updatedAt: now,
      })
      .where(eq(classInstances.id, classInstanceId))
      .returning({ id: classInstances.id });

    if (!deleted) return null;
    return {
      id: deleted.id,
      studentId: existing.studentId,
      quotaDeducted: existing.quotaDeducted,
      quotaId,
      deleted: existing.deletedAt === null,
    };
  };
  return tx ? await runner(tx) : await db.transaction((t: DBTransaction) => runner(t));
}

export async function clearWeeklySchedule(
  teacherId: string,
  tx?: DBTransaction
): Promise<{
  refundedInstances: { id: string; studentId: string }[];
  quotaSchedules: { id: string; studentId: string; quotaId: string; earmarkedClasses: number }[];
} | null> {
  const runner = async (t: DBTransaction) => {
    const now = new Date();

    const schedules = await t
      .select({
        id: recurringSchedules.id,
        studentId: recurringSchedules.studentId,
        quotaId: recurringSchedules.quotaId,
        earmarkedClasses: recurringSchedules.earmarkedClasses,
      })
      .from(recurringSchedules)
      .where(and(eq(recurringSchedules.teacherId, teacherId), isNull(recurringSchedules.deletedAt)));

    if (schedules.length === 0) {
      return null;
    }

    const scheduleIds = schedules.map(s => s.id);

    await t
      .update(recurringScheduleDays)
      .set({ isActive: false })
      .where(inArray(recurringScheduleDays.recurringScheduleId, scheduleIds));

    await t
      .update(recurringSchedules)
      .set({
        deletedAt: now,
        updatedAt: now,
      })
      .where(inArray(recurringSchedules.id, scheduleIds));

    const orphanedInstances = await t
      .select({
        id: classInstances.id,
        quotaDeducted: classInstances.quotaDeducted,
        studentId: classInstances.studentId,
      })
      .from(classInstances)
      .where(
        and(
          inArray(classInstances.recurringScheduleId, scheduleIds),
          isNull(classInstances.deletedAt),
          gte(classInstances.scheduledStartAt, now)
        )
      );

    const refundedInstances = orphanedInstances
      .filter(instance => instance.quotaDeducted)
      .map(instance => ({ id: instance.id, studentId: instance.studentId }));

    if (orphanedInstances.length > 0) {
      await t
        .update(classInstances)
        .set({ deletedAt: now, updatedAt: now })
        .where(
          inArray(
            classInstances.id,
            orphanedInstances.map(i => i.id)
          )
        );
    }

    const quotaSchedules: { id: string; studentId: string; quotaId: string; earmarkedClasses: number }[] = [];
    for (const s of schedules) {
      if (s.quotaId && s.earmarkedClasses && s.earmarkedClasses > 0) {
        quotaSchedules.push({
          id: s.id,
          studentId: s.studentId,
          quotaId: s.quotaId,
          earmarkedClasses: s.earmarkedClasses,
        });
      }
    }

    return { refundedInstances, quotaSchedules };
  };
  return tx ? await runner(tx) : await db.transaction((t: DBTransaction) => runner(t));
}

function getOffsetMinutes(ianaTimezone: string, d: Date): number | null {
  try {
    return Math.round(getTimezoneOffsetMs(ianaTimezone, d) / 60000);
  } catch {
    return null;
  }
}

async function insertRecurringScheduleRow(t: DBTransaction, input: CreateRecurringScheduleInput, now: Date) {
  const utcOffsetSnapshot = getOffsetMinutes(input.timezone, now);

  const [recurringSchedule] = await t
    .insert(recurringSchedules)
    .values({
      studentId: input.studentId,
      teacherId: input.teacherId,
      subjectId: input.subjectId,
      durationMinutes: input.durationMinutes,
      defaultStartTime: input.defaultStartTime,
      timezone: input.timezone,
      timezoneId: input.timezoneId ?? null,
      utcOffsetSnapshot,
      hourlyRate: input.hourlyRate ?? null,
      rateCurrency: input.rateCurrency ?? null,
      effectiveFrom: input.effectiveFrom ? input.effectiveFrom.toISOString().split("T")[0] : null,
      effectiveUntil: input.effectiveUntil ? input.effectiveUntil.toISOString().split("T")[0] : null,
      quotaId: input.quotaId ?? null,
      earmarkedClasses: input.earmarkedClasses ?? null,
      schedulingMode: input.schedulingMode ?? "NUMBER_OF_CLASSES",
      generationHorizonWeeks: input.generationHorizonWeeks ?? null,
      ondemandNoCreditsOutcome: input.ondemandNoCreditsOutcome ?? null,
      createdAt: now,
      updatedAt: now,
    })
    .returning();

  return { recurringSchedule, utcOffsetSnapshot };
}

async function insertScheduleDays(t: DBTransaction, recurringScheduleId: string, input: CreateRecurringScheduleInput) {
  const insertedDays = await t
    .insert(recurringScheduleDays)
    .values(
      input.days.map(day => ({
        recurringScheduleId,
        dayOfWeek: day.dayOfWeek,
        startTime: day.startTime,
        isActive: day.isActive,
      }))
    )
    .returning();
  return insertedDays;
}

type ComputedInstanceRow = {
  scheduledStartAt: Date;
  scheduledEndAt: Date;
  dayOfWeek: string;
  idempotencyKey: string;
};

function computeInstanceRows(
  insertedDays: { dayOfWeek: string; startTime: string; isActive: boolean }[],
  recurringScheduleId: string,
  effectiveStartDate: Date,
  weeksToGenerate: number,
  durationMinutes: number,
  timezone: string
): ComputedInstanceRow[] {
  const instanceRows: ComputedInstanceRow[] = [];

  for (let weekOffset = 0; weekOffset < weeksToGenerate; weekOffset++) {
    for (const day of insertedDays) {
      if (!day.isActive) continue;

      const scheduledStartAt = computeScheduledStartForDay(
        day.dayOfWeek,
        day.startTime,
        effectiveStartDate,
        weekOffset,
        timezone
      );
      const scheduledEndAt = new Date(scheduledStartAt.getTime() + durationMinutes * 60000);
      const idempotencyKey = `recurring-${recurringScheduleId}-${day.dayOfWeek}-${scheduledStartAt.toISOString()}`;

      instanceRows.push({ scheduledStartAt, scheduledEndAt, dayOfWeek: day.dayOfWeek, idempotencyKey });
    }
  }

  return instanceRows;
}

async function validateInstanceBatch(
  t: DBTransaction,
  input: CreateRecurringScheduleInput,
  instanceRows: ComputedInstanceRow[],
  tFuncErrors: ErrorsLabels
): Promise<void> {
  // Validate teacher assignment once with the earliest start date — if the
  // assignment covers the earliest occurrence, it covers all later ones too.
  const earliestStartMs = Math.min(...instanceRows.map(r => r.scheduledStartAt.getTime()));
  const earliestStart = new Date(earliestStartMs);
  await validateTeacherAssignment(t, input.studentId, input.teacherId, earliestStart, tFuncErrors);

  // Batched availability check: 3 queries total instead of 3 per instance.
  await AvailabilityService.validateBookingAvailabilityBatch(
    input.teacherId,
    instanceRows.map(r => ({ startTime: r.scheduledStartAt, endTime: r.scheduledEndAt })),
    t,
    "ar"
  );

  // Per-slot overlap checks against pre-existing committed instances. These
  // run BEFORE any of our batched inserts, so they correctly exclude each
  // other (new in-transaction rows are not visible to the snapshot read).
  // Within the batch, no two slots overlap because each (day, weekOffset)
  // pair maps to a distinct UTC start time.
  // Sequential reduce chain — all iterations share the same DB transaction.
  await instanceRows.reduce(async (prev, row) => {
    await prev;
    return checkOverlaps(
      t,
      {
        studentId: input.studentId,
        teacherId: input.teacherId,
        startTime: row.scheduledStartAt,
        endTime: row.scheduledEndAt,
      },
      tFuncErrors
    );
  }, Promise.resolve());
}

async function insertInstanceBatch(
  t: DBTransaction,
  input: CreateRecurringScheduleInput,
  recurringScheduleId: string,
  instanceRows: ComputedInstanceRow[],
  rateSnapshot: RateSnapshot,
  utcOffsetSnapshot: number | null,
  now: Date
): Promise<string[]> {
  const insertedInstances = await t
    .insert(classInstances)
    .values(
      instanceRows.map(row => ({
        studentId: input.studentId,
        teacherId: input.teacherId,
        subjectId: input.subjectId,
        recurringScheduleId,
        scheduledStartAt: row.scheduledStartAt,
        scheduledEndAt: row.scheduledEndAt,
        bookingTimezone: input.timezone,
        bookingUtcOffset: utcOffsetSnapshot,
        bookingTimezoneId: input.timezoneId ?? null,
        durationMinutes: input.durationMinutes,
        classType: input.classType ?? "REGULAR",
        executionState: "NOT_ACTIVATED",
        outcome: "PENDING",
        quotaDeducted: !!input.quotaDeducted,
        rateAmount: rateSnapshot.rateAmount,
        rateCurrency: rateSnapshot.rateCurrency,
        isRateOverridden: false,
        rateSource: rateSnapshot.rateSource,
        idempotencyKey: row.idempotencyKey,
        createdAt: now,
        updatedAt: now,
      }))
    )
    .returning({ id: classInstances.id });

  return insertedInstances.map(i => i.id);
}

export const createRecurringScheduleWithInstances = async (
  input: CreateRecurringScheduleInput,
  _meetingJoinUrl: string | null,
  rateSnapshot: RateSnapshot,
  tx?: DBTransaction,
  tErrors?: ErrorsLabels
): Promise<{ recurringScheduleId: string; classInstanceIds: string[] }> => {
  const runner = async (t: DBTransaction) => {
    const now = new Date();
    const tFuncErrors = tErrors ?? getServerTranslations("en").errorsTranslations;

    const { recurringSchedule, utcOffsetSnapshot } = await insertRecurringScheduleRow(t, input, now);

    const insertedDays = await insertScheduleDays(t, recurringSchedule.id, input);

    const weeksToGenerate = input.generateInstancesForWeeks ?? 1;
    const effectiveStartDate = input.effectiveFrom ? new Date(input.effectiveFrom) : now;

    // Acquire the teacher+student advisory locks once for the whole batch
    // (pg_advisory_xact_lock is reentrant within the same transaction).
    await acquireLocks(t, input.teacherId, input.studentId);

    // Compute all instance rows up front (no DB hits in the loop), then run
    // availability + overlap validations once per batch, and batch-insert.
    const instanceRows = computeInstanceRows(
      insertedDays,
      recurringSchedule.id,
      effectiveStartDate,
      weeksToGenerate,
      input.durationMinutes,
      input.timezone
    );

    if (instanceRows.length === 0) {
      return {
        recurringScheduleId: recurringSchedule.id,
        classInstanceIds: [],
      };
    }

    await validateInstanceBatch(t, input, instanceRows, tFuncErrors);

    const classInstanceIds = await insertInstanceBatch(
      t,
      input,
      recurringSchedule.id,
      instanceRows,
      rateSnapshot,
      utcOffsetSnapshot,
      now
    );

    return {
      recurringScheduleId: recurringSchedule.id,
      classInstanceIds,
    };
  };

  return tx ? await runner(tx) : await db.transaction((t: DBTransaction) => runner(t));
};
