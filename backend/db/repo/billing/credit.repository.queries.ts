/** Single source of truth for both balance views (avoids query duplication). */
const getStudentQuotaBalancesImpl = async (
  tx?: ReadExecutor,
  studentId?: string
): Promise<{
  classesTotal: number;
  classesRemaining: number;
  creditHoursTotal: string;
  creditHoursRemaining: string;
}> => {
  const { targetStudentId, executor } = resolveStudentScope(tx, studentId);
  const row = await fetchStudentQuotaRow(executor, targetStudentId);
  return {
    classesTotal: row?.classesTotal ?? 0,
    classesRemaining: row?.classesRemaining ?? 0,
    creditHoursTotal: row?.creditHoursTotal ?? "0",
    creditHoursRemaining: row?.creditHoursRemaining ?? "0",
  };
};

/** Thin adapter over the shared balance fetch (class-count view). */
export const getBalanceImpl = async (
  tx?: ReadExecutor,
  studentId?: string
): Promise<{ classesTotal: number; classesRemaining: number }> => {
  const balances = await getStudentQuotaBalancesImpl(tx, studentId);
  return { classesTotal: balances.classesTotal, classesRemaining: balances.classesRemaining };
};

/** Thin adapter over the shared balance fetch (hour view). */
export const getHourBalanceImpl = async (
  tx?: ReadExecutor,
  studentId?: string
): Promise<{ creditHoursTotal: string; creditHoursRemaining: string }> => {
  const balances = await getStudentQuotaBalancesImpl(tx, studentId);
  return { creditHoursTotal: balances.creditHoursTotal, creditHoursRemaining: balances.creditHoursRemaining };
};

export const getTransactionsImpl = async (
  tx: ReadExecutor | string,
  studentId?: string | PaginationArgs | null,
  paginationArgs?: PaginationArgs | null,
  opts?: { hoursOnly?: boolean }
): Promise<CreditTransactionSelectType[]> => {
  const { executor, studentId: actualStudentId } = resolveStudentArgPair(
    tx,
    typeof studentId === "string" ? studentId : undefined
  );
  let actualPagination: PaginationArgs | null;
  if (typeof tx === "string") {
    actualPagination = studentId instanceof PaginationArgs ? studentId : null;
  } else {
    actualPagination = paginationArgs ?? null;
  }
  const q = queryDb(executor);
  const baseQuery = q
    .select()
    .from(creditTransactions)
    .where(buildStudentLedgerFilter(actualStudentId, opts?.hoursOnly))
    .orderBy(desc(creditTransactions.createdAt))
    .$dynamic();
  return queryWithPagination(baseQuery, actualPagination);
};

/** All ledger rows generated by one accounting payment (detail history). */
export const listBySourcePaymentIdImpl = async (
  sourcePaymentId: string,
  tx?: DBTransaction
): Promise<CreditTransactionSelectType[]> => {
  const q = queryDb(tx);
  return q
    .select()
    .from(creditTransactions)
    .where(eq(creditTransactions.sourcePaymentId, sourcePaymentId))
    .orderBy(asc(creditTransactions.createdAt));
};

export const countTransactionsImpl = async (
  tx: ReadExecutor | string,
  studentId?: string,
  opts?: { hoursOnly?: boolean }
): Promise<number> => {
  const { executor, studentId: actualStudentId } = resolveStudentArgPair(tx, studentId);
  const q = queryDb(executor);
  const [row] = await q
    .select({ value: count() })
    .from(creditTransactions)
    .where(buildStudentLedgerFilter(actualStudentId, opts?.hoursOnly));
  return row?.value ?? 0;
};

export const findByIdempotencyKeysImpl = async (
  keys: string[],
  tx?: DBTransaction
): Promise<CreditTransactionSelectType[]> => {
  if (keys.length === 0) return [];
  const q = queryDb(tx);
  return q
    .select()
    .from(creditTransactions)
    .where(inArray(creditTransactions.idempotencyKey, [...keys]));
};

export const findByClassInstanceIdImpl = async (
  tx: ReadExecutor | string,
  classInstanceId?: string | CreditReason,
  reason?: CreditReason
): Promise<CreditTransactionSelectType[]> => {
  const executor = typeof tx === "string" ? undefined : tx;
  const actualClassId = typeof tx === "string" ? tx : classInstanceId;
  if (typeof actualClassId !== "string") {
    throw new DomainError("INVALID_ARGS", "classInstanceId must be a string when tx is not a string");
  }
  let actualReason: CreditReason | undefined;
  if (typeof tx === "string") {
    actualReason = isCreditReason(classInstanceId) ? classInstanceId : undefined;
  } else {
    actualReason = reason;
  }
  const q = queryDb(executor);
  const whereCondition = actualReason
    ? and(eq(creditTransactions.classInstanceId, actualClassId), eq(creditTransactions.reason, actualReason))
    : eq(creditTransactions.classInstanceId, actualClassId);
  return q.select().from(creditTransactions).where(whereCondition);
};

export const aggregateBalanceFromLedgerImpl = async (
  tx: ReadExecutor | string,
  studentId?: string
): Promise<{ classesTotal: number; classesRemaining: number }> => {
  const { executor, studentId: actualStudentId } = resolveStudentArgPair(tx, studentId);
  const q = queryDb(executor);
  const [row] = await q
    .select({
      classesTotal:
        sql<number>`COALESCE(SUM(CASE WHEN ${creditTransactions.reason} = 'PURCHASE' THEN ${creditTransactions.changeAmount} ELSE 0 END), 0)`.mapWith(
          Number
        ),
      classesRemaining: sql<number>`COALESCE(SUM(${creditTransactions.changeAmount}), 0)`.mapWith(Number),
    })
    .from(creditTransactions)
    .where(eq(creditTransactions.studentId, actualStudentId));
  return {
    classesTotal: row?.classesTotal ?? 0,
    classesRemaining: row?.classesRemaining ?? 0,
  };
};

/**
 * Batched dashboard read: sums the manually subtracted credit amount per class
 * instance for SUBTRACT adjustment rows linked to those instances. Subtract rows
 * persist negative deltas, so the map carries the positive subtracted magnitude
 * that the caller can display or add directly. Credit ledger rows carry no
 * currency column, so `currency` is always null here — enrichment from a monetary
 * source (e.g. the session's currency) is the caller's concern. Instances without
 * subtract rows are absent from the map. An empty `instanceIds` input returns an
 * empty map (an `inArray` filter over an empty array is invalid SQL on PostgreSQL).
 */
export const findSubtractCreditsByInstanceIdsImpl = async (
  instanceIds: string[],
  tx?: DBTransaction
): Promise<Map<string, { amount: number; currency: null }>> => {
  if (instanceIds.length === 0) return new Map();
  const q = queryDb(tx);
  const rows = await q
    .select({
      classInstanceId: creditTransactions.classInstanceId,
      subtractedAmount: sql<number>`COALESCE(SUM(ABS(${creditTransactions.changeAmount})), 0)`.mapWith(Number),
    })
    .from(creditTransactions)
    .where(
      and(
        inArray(creditTransactions.classInstanceId, [...instanceIds]),
        eq(creditTransactions.adjustmentType, CreditAdjustmentType.SUBTRACT)
      )
    )
    .groupBy(creditTransactions.classInstanceId);
  const byInstance = new Map<string, { amount: number; currency: null }>();
  for (const row of rows) {
    if (row.classInstanceId) {
      byInstance.set(row.classInstanceId, {
        amount: row.subtractedAmount,
        currency: null,
      });
    }
  }
  return byInstance;
};
